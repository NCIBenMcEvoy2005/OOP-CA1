    private void createEventBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_createEventBTNActionPerformed
        // Create Event Function
        String Name = nameTF.getText();
        String Date = dateTF.getText();
        String Location = locationTF.getText();
        int Attending = Integer.parseInt(attendingTF.getText());
        if(fundraiserBTN.isSelected()){
            String catagory = fundraiserInfoTF.getText();
            if(onlineEventTrueBTN.isSelected()){
                boolean Online = true;
                Fundraisers FEV = new Fundraisers(Online, catagory, Name, Date, Location, Attending);
                currentEvents.add(FEV);
                resultTA.setText("Fundraiser Added!");
                count++;
            }else{
                boolean Online = false;
                Fundraisers FEV = new Fundraisers(Online, catagory, Name, Date, Location, Attending);
                currentEvents.add(FEV);
                resultTA.setText("Fundraiser Added!");
                count++;
            }
            //////////////////////////////////////////
        }else if(volunteeringBTN.isSelected()){
            String catagory = volunteeringCatagoryTF.getText();
            int EventLength = Integer.parseInt(volunteeringEDTF.getText());
            if(volunteeringReoccuringTrueBTN.isSelected()){
                boolean reoccuring = true;
                VolunteeringEvent VE = new VolunteeringEvent(reoccuring, EventLength, catagory,  Name, Date, Location, Attending);
                currentEvents.add(VE);
                resultTA.setText("Volunteering Event Added!");
                count++;
            }else{
                boolean reoccuring = false;
                VolunteeringEvent VE = new VolunteeringEvent(reoccuring, EventLength, catagory,  Name, Date, Location, Attending);
                currentEvents.add(VE);
                resultTA.setText("Volunteering Event Added!");
                count++;
            }
        }
    }//GEN-LAST:event_createEventBTNActionPerformed

    private void searchBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchBTNActionPerformed
        // Search Event Function
        resultTA.setText("");
        String userSearch = searchBarTF.getText();
        if(userSearch != null){
            for(int i = 0;i < currentEvents.size();i++){
                Events ev = currentEvents.get(i);
                if(ev.getName().equals(userSearch)){
                    System.out.println("Match Found!");
                    resultTA.setText(ev.toString());
                }else{
                    System.out.println("No Match, Looping Again");
                }
            }
        }else if(userSearch == null){
            String displayText = "";
            for(int i = 0;i < currentEvents.size();i++){
                Events ev = currentEvents.get(i);
                displayText += ev.toString();
                displayText += "#######################";
            }
            resultTA.setText(displayText);
        }
    }//GEN-LAST:event_searchBTNActionPerformed

